with open('src/gui/loveup/gui.cpp', 'r', encoding='utf-8') as f:
    content = f.read()

def replacer(match):
    en_text = match.group(1)
    if en_text in ru_dict:
        # return f'(const char*)u8"{ru_dict[en_text]}"'
        # Actually wait, using xorstr_((const char*)u8"...") doesn't work well.
        # But wait, without xorstr_ the strings are in plaintext. The user doesn't care.
        return f'(const char*)u8"{ru_dict[en_text]}"'
    return f'(const char*)u8"{en_text}"'

# replace Loc(xorstr_("...")) and Loc(Loc(xorstr_("...")))
# Note: we might have Loc(xorstr_("..."))
content = re.sub(r'Loc\(xorstr_\("([^"]+)"\)\)', replacer, content)

with open('src/gui/loveup/gui.cpp', 'w', encoding='utf-8') as f:
    f.write(content)
