// ─────────────────────────────────────────────────────────────────────────────
// 12. ShellBags 
// ─────────────────────────────────────────────────────────────────────────────
static void WipeShellBagsSelective() {
    std::string exe_name, exe_ne, fp;
    GetSelfExeName(exe_name, exe_ne, fp);

    size_t sl = fp.find_last_of('\\');
    std::string exe_dir = (sl != std::string::npos) ? fp.substr(0, sl) : fp;
    size_t sl2 = exe_dir.find_last_of('\\');
    std::string parent_dir = (sl2 != std::string::npos) ? exe_dir.substr(sl2 + 1) : exe_dir;

    std::vector<std::string> targets = { exe_name, exe_ne, parent_dir,
                                         xorstr_("kdmapper"), xorstr_("pdfwkrnl") };

    auto pidl_contains = [&](const BYTE* data, DWORD len) -> bool {
        for (const auto& t : targets) {
            if (t.empty()) continue;
            for (DWORD i = 0; i + t.size() <= len; i++) {
                bool m = true;
                for (size_t j = 0; j < t.size() && m; j++)
                    m = (toupper((unsigned char)data[i+j]) == toupper((unsigned char)t[j]));
                if (m) return true;
            }
        }
        return false;
    };

    struct BagRoot { std::string bagmru; std::string bags; };
    BagRoot ROOTS[] = {
        { "Software\\Classes\\Local Settings\\Software\\Microsoft\\Windows\\Shell\\BagMRU",
          "Software\\Classes\\Local Settings\\Software\\Microsoft\\Windows\\Shell\\Bags" },
        { "Software\\Microsoft\\Windows\\Shell\\BagMRU",
          "Software\\Microsoft\\Windows\\Shell\\Bags" }
    };

    for (const auto& r : ROOTS) {
        std::function<void(const std::string&)> walk;
        walk = [&](const std::string& node_path) {
            HKEY hNode;
            if (RegOpenKeyExA(HKEY_CURRENT_USER, node_path.c_str(),
                              0, KEY_READ, &hNode) != ERROR_SUCCESS) return;

            char nbuf[64]; DWORD nlen; DWORD idx = 0;
            std::vector<std::string> children, vals;
            while (true) {
                nlen = sizeof(nbuf) - 1;
                if (RegEnumKeyExA(hNode, idx++, nbuf, &nlen,
                                  nullptr, nullptr, nullptr, nullptr) != ERROR_SUCCESS) break;
                children.push_back(std::string(nbuf, nlen));
            }
            idx = 0;
            while (true) {
                nlen = sizeof(nbuf) - 1;
                DWORD type;
                if (RegEnumValueA(hNode, idx++, nbuf, &nlen,
                                  nullptr, &type, nullptr, nullptr) != ERROR_SUCCESS) break;
                if (type == REG_BINARY) vals.push_back(std::string(nbuf, nlen));
            }
            RegCloseKey(hNode);

            for (const auto& child : children)
                walk(node_path + "\\" + child);

            if (RegOpenKeyExA(HKEY_CURRENT_USER, node_path.c_str(),
                              0, KEY_READ | KEY_WRITE, &hNode) != ERROR_SUCCESS) return;

            for (const auto& val : vals) {
                if (val == "NodeSlot" || val == "NodeSlots" || val == "MRUListEx") continue;
                BYTE blob[8192] = {};
                DWORD blob_len = sizeof(blob);
                if (RegQueryValueExA(hNode, val.c_str(), nullptr, nullptr,
                                     blob, &blob_len) != ERROR_SUCCESS) continue;
                if (!pidl_contains(blob, blob_len)) continue;

                RegDeleteValueA(hNode, val.c_str());

                std::string child_path = node_path + "\\" + val;
                HKEY hChild;
                if (RegOpenKeyExA(HKEY_CURRENT_USER, child_path.c_str(),
                                  0, KEY_READ, &hChild) == ERROR_SUCCESS) {
                    DWORD slot = 0, slot_sz = sizeof(slot);
                    RegQueryValueExA(hChild, "NodeSlot", nullptr, nullptr,
                                     (BYTE*)&slot, &slot_sz);
                    RegCloseKey(hChild);
                    if (slot > 0) {
                        char ss[16]; sprintf_s(ss, "%u", slot);
                        std::string bag_path = std::string(r.bags) + "\\" + ss;
                        HKEY hBag;
                        if (RegOpenKeyExA(HKEY_CURRENT_USER, bag_path.c_str(),
                                          0, KEY_READ | KEY_WRITE, &hBag) == ERROR_SUCCESS) {
                            char cn[256]; DWORD cl;
                            while (true) {
                                cl = sizeof(cn) - 1;
                                if (RegEnumKeyExA(hBag, 0, cn, &cl,
                                                  nullptr, nullptr, nullptr, nullptr) != ERROR_SUCCESS) break;
                                RegDeleteKeyA(hBag, cn);
                            }
                            RegCloseKey(hBag);
                            RegDeleteKeyA(HKEY_CURRENT_USER, bag_path.c_str());
                        }
                    }
                }
                RegDeleteKeyA(HKEY_CURRENT_USER, child_path.c_str());
            }
            RegCloseKey(hNode);
        };
        walk(r.bagmru);
    }
}

