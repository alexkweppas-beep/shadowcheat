// ─────────────────────────────────────────────────────────────────────────────
static DWORD g_recentdocs_saved   = 0;
static bool  g_recentdocs_existed = false;

static void WipeUserAssist() {
    std::string exe_name, exe_ne, fp;
    GetSelfExeName(exe_name, exe_ne, fp);

    auto rot13 = [](std::string s) -> std::string {
        for (char& c : s) {
            if (c >= 'a' && c <= 'z') c = (char)('a' + (c - 'a' + 13) % 26);
            else if (c >= 'A' && c <= 'Z') c = (char)('A' + (c - 'A' + 13) % 26);
        }
        return s;
    };

    const std::string UA_COUNTS[] = {
        "Software\\Microsoft\\Windows\\CurrentVersion\\Explorer\\UserAssist\\{CEBFF5CD-ACE2-4F4F-9178-9926F41749EA}\\Count",
        "Software\\Microsoft\\Windows\\CurrentVersion\\Explorer\\UserAssist\\{F4E57C4B-2036-45F0-A9AB-443BCFE33D9F}\\Count",
        ""
    };

    for (const auto& ua : UA_COUNTS) {
        if (ua.empty()) continue;
        HKEY hUA;
        if (RegOpenKeyExA(HKEY_CURRENT_USER, ua.c_str(),
                          0, KEY_READ | KEY_WRITE, &hUA) != ERROR_SUCCESS) continue;

        char vname[1024]; DWORD vlen; DWORD idx = 0;
        std::vector<std::string> bad;
        while (true) {
            vlen = sizeof(vname) - 1;
            if (RegEnumValueA(hUA, idx++, vname, &vlen,
                              nullptr, nullptr, nullptr, nullptr) != ERROR_SUCCESS) break;
            std::string decoded = rot13(std::string(vname, vlen));
            if (IsOurTrace(decoded, exe_name, exe_ne))
                bad.push_back(std::string(vname, vlen));
        }
        for (const auto& v : bad) RegDeleteValueA(hUA, v.c_str());
        RegCloseKey(hUA);
    }
}

